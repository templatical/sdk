// Writes the package's generated assets:
//
// - prompts/operations.md, a byte copy of apps/docs/api/operations.md: the
//   operation vocabulary the editing prompt teaches (Cloud's MCP server serves
//   the same file);
// - src/generated/assets.ts, every prompt and schema file as a string
//   constant, so the isomorphic source never reads a file at run time.
//
// schema/template-content.schema.json is NOT written here: template-tools'
// generate-schema writes it with the other copies of the one schema.
//
//   pnpm --filter @templatical/ai-kit run generate-assets
//
// `--check` exits 1 instead of writing when a file is stale. The freshness
// test imports buildAssetsModule() and compares.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
// The repo's own Prettier (a root devDependency): the module is written the way
// `pnpm run format` would write it, so formatting never makes it stale.
import { format } from "prettier";

const pkg = join(import.meta.dirname, "..");
const repo = join(pkg, "../..");

export const OPERATIONS_SOURCE = join(repo, "apps/docs/api/operations.md");
export const OPERATIONS_COPY = join(pkg, "prompts/operations.md");
export const ASSETS_MODULE_PATH = join(pkg, "src/generated/assets.ts");

const read = (rel) => readFileSync(join(pkg, rel), "utf8");
/** A prompt file without its one trailing newline. */
const prompt = (rel) => read(rel).replace(/\n$/, "");
const json = (rel) => JSON.parse(read(rel));

/** The constants, in the order the module declares them. */
function constants() {
  return [
    ["EDITING_RULES", prompt("prompts/editing.md")],
    ["OPERATIONS_GUIDE", readFileSync(OPERATIONS_SOURCE, "utf8")],
    ["TEMPLATE_CONTENT_SCHEMA", read("schema/template-content.schema.json")],
    ["CHAT_REQUEST", prompt("prompts/chat.md")],
    ["FIX_REQUEST", prompt("prompts/fix.md")],
    ["CHAT_ATTACHMENTS", prompt("prompts/chat-attachments.md")],
    ["ALT_TEXT_INSTRUCTIONS", prompt("prompts/alt-text.md")],
    ["REWRITE_INSTRUCTIONS", prompt("prompts/rewrite.md")],
  ];
}

export async function buildAssetsModule() {
  const lines = [
    "// Generated by scripts/generate-assets.mjs from prompts/ and schema/.",
    "// Don't edit: change the files and run",
    "// `pnpm --filter @templatical/ai-kit run generate-assets`.",
    "",
  ];
  for (const [name, value] of constants()) {
    lines.push(`export const ${name} = ${JSON.stringify(value)};`, "");
  }
  lines.push(
    `export const FIX_RULE_GUIDANCE = ${JSON.stringify(json("prompts/fix-rules.json"))} as const;`,
    "",
    `export const REWRITE_PRESETS = ${JSON.stringify(json("prompts/rewrite-presets.json"))} as const;`,
    "",
    "",
    "",
  );
  return format(lines.join("\n"), { parser: "typescript" });
}

if (process.argv[1] === import.meta.filename) {
  const operations = readFileSync(OPERATIONS_SOURCE, "utf8");
  const module = await buildAssetsModule();
  if (process.argv.includes("--check")) {
    const stale = [
      [OPERATIONS_COPY, operations],
      [ASSETS_MODULE_PATH, module],
    ].filter(([path, fresh]) => {
      try {
        return readFileSync(path, "utf8") !== fresh;
      } catch {
        return true;
      }
    });
    if (stale.length > 0) {
      console.error(
        "Stale: " +
          stale.map(([path]) => path).join(", ") +
          ". Run: pnpm --filter @templatical/ai-kit run generate-assets",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OPERATIONS_COPY, operations);
    mkdirSync(dirname(ASSETS_MODULE_PATH), { recursive: true });
    writeFileSync(ASSETS_MODULE_PATH, module);
    console.log(`Wrote ${OPERATIONS_COPY} and ${ASSETS_MODULE_PATH}`);
  }
}
