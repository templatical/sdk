// Bundles the skill's runtime dependencies into vendor/*.mjs — single
// dependency-free ESM files that scripts/validate.mjs imports directly.
//
// Why vendor at all: the skill runs from Claude Code's plugin cache, which is
// keyed by plugin VERSION. Every update lands in a fresh, empty directory, so
// whatever the user `npm install`ed into the previous one is gone. Validation
// then broke silently until they reinstalled — for every user, on every update.
// Vendoring keeps `node scripts/validate.mjs` working on a clean install and
// offline, the same zero-dependency stance scripts/live-server.mjs takes.
//
// Bundling ajv (~115 KB) rather than precompiling the schema into standalone
// validators (~400-540 KB, since each embeds its own copy of the definitions)
// keeps the artifact small AND leaves validate.mjs's logic untouched: it still
// compiles reference/schema.json at runtime (~18 ms), so discriminator-aware
// error paths behave exactly as before.
//
// Run: pnpm --filter @templatical/email-skill run bundle-vendor
// Release-time: tools/sync-editor-version.mjs re-bundles and patch-bumps the
// plugin when the output changes, so a @templatical/quality release reaches
// installed skills. tests/vendor-freshness.test.ts fails CI on drift.
import { build } from "esbuild";
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const packages = resolve(here, "../../../packages");

export const VENDOR_DIR = resolve(here, "../vendor");

/**
 * What gets vendored. `entry` is bundled from source for workspace packages (so
 * a build of the workspace isn't required) and from the installed package for
 * externals.
 */
export const TARGETS = [
  {
    name: "ajv",
    file: "ajv.mjs",
    contents: 'import Ajv from "ajv";\nexport default Ajv;\n',
    notice:
      "MIT License, Copyright (c) 2015-2021 Evgeny Poberezkin\n// https://github.com/ajv-validator/ajv/blob/master/LICENSE",
    version: () =>
      JSON.parse(readFileSync(require.resolve("ajv/package.json"), "utf8"))
        .version,
  },
  {
    name: "@templatical/quality",
    file: "quality.mjs",
    // Bundled from dist, NOT src: the rule/message registries use Vite's
    // `import.meta.glob`, which esbuild does not implement — bundling the source
    // produces a file that throws "(intermediate value).glob is not a function"
    // on import. Vite resolves those globs at build time, so dist is the only
    // input that works. Hence `requires`, checked before the build runs.
    contents: `export * from ${JSON.stringify(resolve(packages, "quality/dist/index.js"))};\n`,
    requires: {
      path: resolve(packages, "quality/dist/index.js"),
      hint: "pnpm --filter @templatical/quality build",
    },
    notice:
      "MIT License, Copyright (c) Templatical — bundles htmlparser2 (MIT)\n// https://github.com/templatical/sdk",
    version: () =>
      JSON.parse(readFileSync(resolve(packages, "quality/package.json"), "utf8"))
        .version,
  },
];

/**
 * Pure: the banner prepended to a bundle. Carries the dependency's licence (the
 * bundle redistributes third-party code) and the version, which
 * tests/vendor-freshness.test.ts parses to detect drift.
 */
export function buildBanner({ name, version, notice }) {
  return [
    "// @generated by tools/bundle-vendor.mjs — do not edit.",
    `// Bundled dependency: ${name} v${version} — ${notice}`,
    `// vendored-version: ${version}`,
    "// Regenerate: pnpm --filter @templatical/email-skill run bundle-vendor",
    "",
  ].join("\n");
}

/** Parse a bundle's recorded version, or null when the banner is absent. */
export function vendoredVersion(source) {
  return /^\/\/ vendored-version: (.+)$/m.exec(source)?.[1] ?? null;
}

/**
 * Rebuild every vendor bundle.
 * @returns {Promise<Array<{ name: string, file: string, version: string, bytes: number, changed: boolean }>>}
 */
export async function bundleVendor() {
  mkdirSync(VENDOR_DIR, { recursive: true });
  const results = [];

  for (const target of TARGETS) {
    if (target.requires && !existsSync(target.requires.path)) {
      throw new Error(
        `Cannot bundle ${target.name}: ${target.requires.path} is missing.\n` +
          `Build it first:\n  ${target.requires.hint}`,
      );
    }
    const version = target.version();
    const result = await build({
      stdin: {
        contents: target.contents,
        resolveDir: here,
        sourcefile: "vendor-entry.mjs",
      },
      bundle: true,
      minify: true,
      format: "esm",
      platform: "node",
      target: "node18",
      // Workspace packages import each other by name; resolve to source so this
      // never depends on the packages being built first.
      alias: {
        "@templatical/types": resolve(packages, "types/src/index.ts"),
        "@templatical/core": resolve(packages, "core/src/index.ts"),
      },
      // Keep upstream licence headers alongside our banner.
      legalComments: "eof",
      banner: { js: buildBanner({ ...target, version }) },
      write: false,
    });

    const [out] = result.outputFiles;
    const path = resolve(VENDOR_DIR, target.file);
    const previous = existsSync(path) ? readFileSync(path, "utf8") : null;
    const changed = previous !== out.text;
    if (changed) {
      writeFileSync(path, out.text, "utf8");
    }
    results.push({
      name: target.name,
      file: target.file,
      version,
      bytes: out.text.length,
      changed,
    });
  }

  return results;
}

async function main() {
  for (const r of await bundleVendor()) {
    console.log(
      `${r.changed ? "Wrote" : "Unchanged"} vendor/${r.file} — ${r.name} v${r.version} (${(r.bytes / 1024).toFixed(0)} KB)`,
    );
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
